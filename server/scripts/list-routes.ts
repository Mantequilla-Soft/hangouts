/**
 * List every HTTP route the API server registers, straight from the Fastify
 * route registrations (no hand-kept list can drift from the code).
 *
 * Usage (from server/):
 *   npx tsx scripts/list-routes.ts                    Markdown table on stdout
 *   npx tsx scripts/list-routes.ts --json             JSON on stdout
 *   npx tsx scripts/list-routes.ts --write <file.md>  Rewrite the table between
 *                                                     the route markers in a doc
 *   npx tsx scripts/list-routes.ts --check <file.md>  Exit 1 when that table is
 *                                                     out of date (for CI)
 *
 * It builds the app with dummy settings: no .env is read, no database or
 * LiveKit connection is opened, nothing listens on a port.
 */

import { readFileSync, writeFileSync } from 'node:fs';

// Dummy settings, forced, so a real .env (and its keys) is never loaded.
process.env.DOTENV_CONFIG_PATH = '/nonexistent/.env';
Object.assign(process.env, {
  LIVEKIT_HOST: 'http://127.0.0.1:7880',
  LIVEKIT_API_KEY: 'list-routes',
  LIVEKIT_API_SECRET: 'list-routes',
  SESSION_SECRET: 'list-routes-dummy-secret-0123456789abcdef',
  MONGODB_URI: '',
  STREAM_STATS_SECRET: '',
  BOOSTS_ENABLED: 'false',
});

const START = '<!-- routes:start (generated by server/scripts/list-routes.ts, do not edit by hand) -->';
const END = '<!-- routes:end -->';

interface RouteRow {
  method: string;
  path: string;
  preHandler: string[];
  rateLimit: string;
  query: string;
  body: string;
}

type Schema = { type?: unknown; properties?: Record<string, Schema>; required?: string[]; enum?: unknown[]; items?: Schema };

function typeOf(s: Schema | undefined): string {
  if (!s) return '';
  if (Array.isArray(s.enum)) return s.enum.map(String).join('|');
  if (Array.isArray(s.type)) return s.type.join('|');
  if (s.type === 'array') return `${typeOf(s.items) || 'any'}[]`;
  return typeof s.type === 'string' ? s.type : '';
}

function fields(s: Schema | undefined): string {
  if (!s?.properties) return '';
  const req = new Set(s.required ?? []);
  return Object.entries(s.properties)
    .map(([k, v]) => `${k}${req.has(k) ? '*' : ''}${typeOf(v) ? `: ${typeOf(v)}` : ''}`)
    .join(', ');
}

function fnNames(h: unknown): string[] {
  const list = Array.isArray(h) ? h : h ? [h] : [];
  return list.map((f) => (typeof f === 'function' && f.name ? f.name : 'anonymous'));
}

function rateLimitOf(cfg: unknown): string {
  const rl = (cfg as { rateLimit?: { max?: unknown; timeWindow?: unknown } } | undefined)?.rateLimit;
  if (!rl) return '';
  const max = typeof rl.max === 'function' ? 'dynamic' : String(rl.max ?? '?');
  const win = typeof rl.timeWindow === 'number' ? `${rl.timeWindow / 1000} s` : String(rl.timeWindow ?? '?');
  return `${max} / ${win}`;
}

async function collect(): Promise<RouteRow[]> {
  const { buildApp } = await import('../src/app.js');
  const rows: RouteRow[] = [];
  const app = await buildApp({
    logger: false,
    onRoute: (r) => {
      if (r.url === '*') return; // the CORS preflight catch-all
      const methods = (Array.isArray(r.method) ? r.method : [r.method]).filter((m) => m !== 'HEAD');
      const schema = r.schema as { body?: Schema; querystring?: Schema } | undefined;
      for (const method of methods) {
        rows.push({
          method,
          path: r.url,
          preHandler: fnNames(r.preHandler),
          rateLimit: rateLimitOf(r.config),
          query: fields(schema?.querystring),
          body: fields(schema?.body),
        });
      }
    },
  });
  await app.close();
  const order = (p: string) => p.replace(/:/g, '~');
  return rows.sort((a, b) => order(a.path).localeCompare(order(b.path)) || a.method.localeCompare(b.method));
}

function markdown(rows: RouteRow[]): string {
  const esc = (s: string) => s.replace(/\|/g, '\\|');
  const out = [
    `${rows.length} routes.`,
    '',
    '| Method | Path | preHandler | Rate limit | Query | Body (`*` = required) |',
    '|---|---|---|---|---|---|',
  ];
  for (const r of rows) {
    out.push(`| ${r.method} | \`${r.path}\` | ${r.preHandler.join(', ') || 'none'} | ${r.rateLimit || 'none'} | ${esc(r.query)} | ${esc(r.body)} |`);
  }
  return out.join('\n');
}

function replaceBlock(doc: string, table: string, file: string): string {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${file}: route markers not found`);
  return `${doc.slice(0, a + START.length)}\n${table}\n${doc.slice(b)}`;
}

const rows = await collect();
const [flag, file] = process.argv.slice(2);
if (flag === '--json') {
  console.log(JSON.stringify(rows, null, 2));
} else if ((flag === '--write' || flag === '--check') && file) {
  const doc = readFileSync(file, 'utf8');
  const next = replaceBlock(doc, markdown(rows), file);
  if (flag === '--write') {
    writeFileSync(file, next);
    console.log(`${file}: ${rows.length} routes written`);
  } else if (next !== doc) {
    console.error(`${file} is out of date: run npx tsx scripts/list-routes.ts --write ${file}`);
    process.exit(1);
  } else {
    console.log(`${file}: route table is up to date (${rows.length} routes)`);
  }
} else {
  console.log(markdown(rows));
}
process.exit(0);
